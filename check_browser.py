"""Run UI checks against a temporary database and an ephemeral local server."""
from pathlib import Path
import re
import tempfile
import threading
from playwright.sync_api import sync_playwright, expect
import server

with tempfile.TemporaryDirectory() as directory:
    server.DB=Path(directory)/'browser.sqlite3'
    server.initialize()
    p=server.new_project('Example software project','Software')
    p['suggestion']={'text':'Outline the first milestone','reason':'No milestone chosen yet.','source':'Project setup'}
    p['chats']=[{'id':'test-chat','title':'Example planning conversation','url':'codex://threads/test-chat','at':'2026-10-29T09:00:00+00:00'}]
    server.event(p,'2026-10-29T09:00:00+00:00','Example planning conversation','Codex chat activity','codex:test-chat')
    server.save(p)
    target=server.new_project('Target Website','Website',identity='target'); target['codexProjectId']='target'; server.save(target)
    http=server.ThreadingHTTPServer(('127.0.0.1',0),server.Handler)
    worker=threading.Thread(target=http.serve_forever,daemon=True); worker.start()
    try:
        with sync_playwright() as browser_tool:
            browser=browser_tool.chromium.launch(headless=True)
            page=browser.new_page(viewport={'width':1100,'height':900})
            errors=[]
            page.on('pageerror',lambda error: errors.append(str(error)))
            page.goto(f'http://127.0.0.1:{http.server_port}')
            page.wait_for_load_state('networkidle')
            card=page.locator('article.project').filter(has=page.get_by_role('heading',name='Example software project',exact=True))
            card.get_by_role('button',name='Accept',exact=True).click()
            expect(card.locator('.next')).to_contain_text('Outline the first milestone')
            expect(card.locator('.activity')).to_contain_text('Example planning conversation')
            card.get_by_role('button',name='Mark done manually',exact=True).click()
            completer=page.locator('#completer')
            completer.get_by_role('button',name='Cancel',exact=True).click()
            expect(card.locator('.next')).to_contain_text('Outline the first milestone')
            expect(card.locator('.completed-history')).to_have_count(0)
            card.get_by_role('button',name='Mark done manually',exact=True).click()
            completer.get_by_label('Completion note (optional)',exact=True).fill('Milestone outline saved')
            completer.get_by_label('Next action (optional)',exact=True).fill('Build the first screen')
            completer.get_by_role('button',name='Mark done manually',exact=True).click()
            expect(page.locator('#notice')).to_have_text('Action completed. Progress recorded.')
            expect(card.locator('.next')).to_contain_text('Build the first screen')
            expect(card.locator('.activity')).to_contain_text('Completed: Outline the first milestone')
            expect(card.locator('.completed-history')).to_contain_text('Milestone outline saved')
            page.reload(); page.wait_for_load_state('networkidle')
            expect(card.locator('.next')).to_contain_text('Build the first screen')
            card.get_by_role('button',name='Mark done manually',exact=True).click()
            completer.get_by_role('button',name='Mark done manually',exact=True).click()
            expect(page.locator('#notice')).to_have_text('Action completed. Progress recorded.')
            expect(card.locator('.next')).to_contain_text('Choose your next step')
            expect(card.get_by_role('button',name='Mark done manually',exact=True)).to_have_count(0)
            expect(card.get_by_text('Completed actions (2)',exact=True)).to_be_visible()
            page.get_by_role('button',name='+ Add project').click()
            editor=page.locator('#editor')
            editor.get_by_label('Project name').fill('New business idea')
            editor.get_by_label('Type',exact=True).select_option('Documents Render')
            expect(editor.get_by_label('Local agency')).to_be_visible()
            editor.get_by_label('Local agency').fill('Example County Library')
            editor.get_by_label('Next action',exact=True).fill('Talk to three potential customers')
            editor.get_by_role('button',name='Save project').click()
            expect(page.locator('#notice')).to_have_text('Project saved.')
            page.get_by_role('searchbox').fill('New business idea')
            expect(page.locator('article.project')).to_have_count(1)
            page.locator('article.project').get_by_role('button',name='Log activity').click()
            page.get_by_label('Planning or progress').fill('Outlined customer interview questions <script>alert(1)</script>')
            page.locator('#logger').get_by_role('button',name='Log activity').click()
            expect(page.locator('#notice')).to_have_text('Activity recorded.')
            expect(page.locator('.activity')).to_contain_text('Outlined customer interview questions')
            page.reload(); page.wait_for_load_state('networkidle')
            page.get_by_role('searchbox').fill('New business idea')
            expect(page.locator('.next')).to_contain_text('Talk to three potential customers')
            expect(page.locator('.activity')).to_contain_text('<script>alert(1)</script>')
            expect(page.locator('.kind')).to_contain_text('Documents Render — Example County Library')
            page.locator('article.project').get_by_role('button',name='Edit project',exact=True).click()
            expect(editor.get_by_label('Local agency')).to_have_value('Example County Library')
            assert editor.locator('#agency-options option').get_attribute('value')=='Example County Library'
            editor.get_by_label('Type',exact=True).select_option('App')
            expect(editor.get_by_label('Local agency')).not_to_be_visible()
            editor.get_by_role('button',name='Cancel',exact=True).click()
            page.get_by_role('searchbox').fill('Example software project')
            page.locator('article.project').get_by_role('button',name='Edit project',exact=True).click()
            editor.get_by_role('button',name='Move chat',exact=True).click()
            mover=page.locator('#mover')
            mover.get_by_label('Destination project',exact=True).select_option('target')
            expect(mover.get_by_role('checkbox')).to_be_checked()
            mover.get_by_role('button',name='Move in tracker',exact=True).click()
            expect(page.locator('#move-result')).to_be_visible()
            expect(page.locator('#native-instruction')).to_contain_text('actual Codex move is still pending')
            expect(page.locator('#move-instruction')).to_have_value(re.compile('test-chat'))
            page.locator('#move-result').get_by_role('button',name='Close dialog').click()
            page.get_by_role('searchbox').fill('Target Website')
            expect(page.locator('article.project').get_by_role('button',name='Finish Codex move')).to_be_visible()
            expect(page.locator('.activity')).to_contain_text('Example planning conversation')
            page.set_viewport_size({'width':390,'height':850})
            assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
            assert not errors,errors
            browser.close()
        print('PASS: completion/cancel/history/reload/optional replacement, suggestion review, agency entry/reuse, chat move, saved activity, narrow panel, no browser errors')
    finally:
        http.shutdown(); http.server_close(); worker.join()
